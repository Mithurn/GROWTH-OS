export async function seedProducts(supabase: any) {
  console.log('🌱 Seeding products...');

  const { data, error } = await supabase
    .from('products')
    .upsert(fashionProducts.map(p => ({
      sku: p.sku,
      product_name: p.name,
      category: p.category,
      subcategory: p.subcategory,
      price: p.price
    })), { onConflict: 'sku' })
    .select();

  if (error) {
    console.error('❌ Error seeding products:', error);
    throw error;
  }

  console.log(`✅ Seeded ${data.length} products`);
  return data;
}
